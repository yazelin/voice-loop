#!/usr/bin/env python3
"""台灣國語語音與用詞前處理器（消除大陸腔、修正兩岸聲調、平舌化、去兒化音）。

層次：
1. 詞彙台灣化（LEXICON_SUBS）：視頻->影片、內存->記憶體、默認->預設、這兒->這裡...
2. 聲調與破音字修正（PRONUNCIATION_SUBS）：垃圾->勒瑟、我和->我汗、企業->氣業、品質->品直、星期->星旗...
"""
import re

# 1. 科技與日常用語替換（文字與語意）
LEXICON_SUBS = [
    ("視頻", "影片"),
    ("軟件", "軟體"),
    ("硬件", "硬體"),
    ("內存", "記憶體"),
    ("服務器", "伺服器"),
    ("默認", "預設"),
    ("信息", "訊息"),
    ("項目", "專案"),
    ("打印", "列印"),
    ("登錄", "登入"),
    ("支持", "支援"),
    ("出租車", "計程車"),
    ("方便麵", "泡麵"),
    ("創口貼", "OK繃"),
    # 兒化音去除
    ("這兒", "這裡"),
    ("哪兒", "哪裡"),
    ("那兒", "那裡"),
    ("一會兒", "一下"),
    ("玩兒", "玩"),
    ("聊天兒", "聊天"),
]

# 2. 兩岸聲調與破音字替換（讓 TTS 模型發出正宗台灣聲調）
PRONUNCIATION_SUBS = [
    ("垃圾", "勒瑟"),
    ("我和你", "我汗你"),
    ("我和", "我汗"),
    ("企業", "氣業"),
    ("企圖", "氣圖"),
    ("品質", "品直"),
    ("質量", "直量"),
    ("亞洲", "訝洲"),
    ("包括", "包刮"),
    ("括號", "刮號"),
    ("角色", "決色"),
    ("主角", "主決"),
    ("液體", "意體"),
    ("血液", "血意"),
    ("星期", "星旗"),
    ("期待", "旗待"),
    ("定期", "定旗"),
    ("微波", "為波"),
    ("微糖", "為糖"),
    ("微冰", "為冰"),
    ("微妙", "為妙"),
    ("結束", "潔束"),
    ("結果", "潔果"),
    ("暫時", "站時"),
    ("暫停", "站停"),
    ("攜帶", "西帶"),
    ("攜手", "西手"),
    ("打擊", "打急"),
    ("攻擊", "攻急"),
]


def taiwanize_text(text: str, for_speech: bool = True) -> str:
    """轉換文字。for_speech=True 時會套用破音字聲調替換（給 TTS 發音用）；
    for_speech=False 時只做正常詞彙台灣化（給螢幕顯示用）。"""
    for k, v in LEXICON_SUBS:
        text = text.replace(k, v)
    if for_speech:
        for k, v in PRONUNCIATION_SUBS:
            text = text.replace(k, v)
    return text
